#include <unistd.h>

/*
  打印所有由 n 个不同数字（0–9）组成、严格递增、不重复的组合，并按字典顺序从小到大输出

  什么是字典顺序？
  1- 单词中字母比较不区分大小写，两个单词先以第一个字母作为排序的基准，
    如果第一个字母相同， 就用第二个字母为基准，
    如果第二个字母相同就以第三个字母为基准。依此类推，
    如果到某个字母不相同，字母顺序在前的那个单词顺序在前
  2- 数字按字典顺序排序，本质上不是把数字当作数值来比较大小，而是把数字当作字符串来比较每一位字符
     先把数字转成字符串，然后按字符从左到右逐个比较，短的靠前，同长度比较第一处不同字符的大小
     就像查英文字典一样："ab" < "abc"（短的在前面), "abc" < "abd"（不同字符比较), 数字字典排序完全遵循这个规则

  假设有一组数字：[1, 2, 10, 11, 12, 3, 20, 21, 100]
  1- 数值排序（从小到大), 比较的是数字的真实大小：1, 2, 3, 10, 11, 12, 20, 21, 100
  2- 字典顺序：1, 10, 100, 11, 12, 2, 20, 21, 3

*/
// 输出数字组合的函数
// n指组合由几个数字组成(即组合的长度)
// first 标记是否是第一个组合，如果不是，第一个数字前会加逗号
// 注意first 可以是 1个数字 或 1个数字组合(n>=2时)
void print_comb(int *arr, int n, int first)
{
  int i;
  char c;

  i = 0;
  if (!first)
    write(1, ", ", 2);
  while (i < n) // 每个数字组合当成是一个字符数组进行输出显示
  {
    c = arr[i] + '0';
    write(1, &c, 1);
    i++;
  }
}

// 负责按字典序生成每一个合法组合
// 从最小组合开始，每次找到最右边还能变大的那一位，把它加1，
// 然后把右边全部重置成最小递增值；直到没有任何一位还能变大为止
// n 是每个数字组合的位数(即数字本身是几位的或长度)
void solve(int *arr, int n)
{
  int first; // 标记当前是否是第一个数字组合
  int i;

  first = 1;
  // 使用死循环是因为循环次数不可提前确定，它取决于 n 和组合的总数；
  // 退出条件是数组已经没有下一组组合可生成，用死循环+内部 break 最清晰
  while (1)
  {
    print_comb(arr, n, first);
    first = 0;
    i = n - 1; // 让 i 指向当前数字组合的最后一位（最低权位）
    // i >= 0 → 防止数组越界，i >= 0 → 找到可增数字，i < 0 → 没有可增数字
    while (i >= 0 && arr[i] == 10 - (n - i)) // 组合里最大值的数字公式：10 - (n - i)
      i--;
    if (i < 0) // 如果 i < 0，说明所有数字都达到最大值，没有下一组合可生成
      break;
    arr[i]++;
    i++;
    while (i < n)
    {
      arr[i] = arr[i - 1] + 1;
      i++;
    }
  }
}

void ft_print_combn(int n)
{
  int i;
  int arr[10];

  if (n <= 0 || n >= 10)
    return;

  i = 0;
  while (i < n) // 初始化第1个最小的合法n位数字的组合
  {
    arr[i] = i;
    i++;
  }
  solve(arr, n); // 
}


#include <stdio.h>

int main()
{
  ft_print_combn(2);
  printf("\n\n");
  ft_print_combn(3);
  printf("\n\n");
  ft_print_combn(9);
  printf("\n\n");
  ft_print_combn(1);
  return (0);
}
